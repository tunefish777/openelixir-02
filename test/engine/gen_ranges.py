"""Extract the UI's value ranges from <root>/Core/Src/menu/menu.c into a C file:
parameter_dtypes[] and getMaxEntriesForMenu(), plus harness_valueRange().
Usage: gen_ranges.py <repo root> <output .c>"""
import re, sys
root, out = sys.argv[1], sys.argv[2]
src = open(root + '/Core/Src/menu/menu.c', errors='replace').read().replace('\r', '')

def block(start_pat):
    m = re.search(start_pat, src, re.M)
    if not m:
        sys.exit('pattern not found: ' + start_pat)
    i = src.index('{', m.end() - 1)
    depth = 0
    for j in range(i, len(src)):
        depth += {'{': 1, '}': -1}.get(src[j], 0)
        if depth == 0:
            return src[m.start():j + 1]

dtypes = block(r'^const enum Datatypes PROGMEM parameter_dtypes\[NUM_PARAMS\] = \{')
maxent = block(r'^static uint8_t getMaxEntriesForMenu\(uint8_t menuId\)\s*\{')
open(out, 'w').write('''/* generated by gen_ranges.py from menu.c: value ranges the UI can send */
#include "stm32f7xx_hal.h"
#include "menu/menu.h"
#include "menu/MenuText.h"
#include "Parameters.h"
uint8_t menu_numSamples = 0;
%s;
%s
void harness_valueRange(uint16_t par, uint8_t* min, uint8_t* max)
{
	const unsigned t = parameter_dtypes[par] & 0xff;
	*min = 0;
	*max = 127;
	switch(t)
	{
	case DTYPE_MENU: *max = (uint8_t)(getMaxEntriesForMenu(parameter_dtypes[par] >> 8) - 1); break;
	case DTYPE_1B16: *min = 1; *max = 16; break;
	case DTYPE_ON_OFF:
	case DTYPE_0b1: *max = 1; break;
	case DTYPE_0B15: *max = 15; break;
	case DTYPE_1B64: *min = 1; *max = 64; break;
	case DTYPE_0B100: *max = 100; break;
	case DTYPE_VOICE_LFO: *min = 1; *max = 6; break;
	default: break;
	}
}
''' % (dtypes, maxent))
